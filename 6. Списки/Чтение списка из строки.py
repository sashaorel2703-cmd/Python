nums = list(map(int, input().split()))
# input() - читает строку с клавиатуры (возвращает строку)
# .split() - разделяет строку на части по пробелам (возвращает список строк)
# map(int, список строк) - применяет к каждому элементу списка функцию int (возвращает коллекцию чисел)
# list() - преобразует результат функции map в список (возвращает список)
print(nums)

